 assert.deepEqual(saves[0].body.preview_preferences,{mode:'auto',pending_recipe:true});
 assert.equal(await page.locator('.version-name h2').innerText(),'Before changing the spacing');
 assert.doesNotMatch(await page.locator('#detail').innerText(),/\p{Script=Han}/u,'English saved draft has no untranslated Chinese copy');
 const selectedContext=await page.evaluate(()=>({project:state.project.id,sha:state.selected,tab:state.tab}));
 await setLanguage('zh');
 assert.deepEqual(await page.evaluate(()=>({project:state.project.id,sha:state.selected,tab:state.tab})),selectedContext,'Language change preserves the selected project, draft and tab');
 assert.equal(await page.locator('.version-name h2').innerText(),'Before changing the spacing','User-entered draft name is preserved');
 assert.match(await page.locator('#detail').innerText(),/取出这一稿/);
 await page.screenshot({path:fixture.root+'/first-draft-zh.png'});
 await setLanguage('en');
 assert.deepEqual(await page.evaluate(()=>({project:state.project.id,sha:state.selected,tab:state.tab})),selectedContext);
 await page.screenshot({path:fixture.root+'/first-draft-en.png'});
 assert.equal(await page.evaluate(()=>state.project.preview_preferences.mode),'auto');
 assert.equal(await page.evaluate(()=>state.project.preview_preferences.pending_recipe),undefined);
 assert.equal(await page.locator('[data-action=remember-draft-preview]').count(),0,'The first answer already covers future saves');
 await page.keyboard.press('ControlOrMeta+s');
 await page.waitForFunction(()=>state.jobs.some(j=>j.operation==='snapshot'&&j.status==='complete'&&j.result?.unchanged),undefined,{timeout:30000});
 assert.equal(await page.evaluate(()=>state.commits.length),1,'Unchanged quick save reuses the original draft');
 assert.equal(await page.locator('#dialog').evaluate(e=>e.open),false,'A remembered project preference enables direct saving');
 const quick=requests.filter(r=>/\/snapshot$/.test(r.url));
 assert.equal(quick.length,2,'One shortcut sends one request');
 assert.equal(quick[1].body.capture_static,false,'Quick save follows the explicit automatic preference');
 assert.deepEqual(await page.evaluate(()=>({project:state.project.id,sha:state.selected,tab:state.tab})),selectedContext,'A background save preserves the selected version');
