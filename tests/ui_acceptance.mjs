/* Empty workspace -> native-bridge fixture -> named draft -> real image -> stop.
   Only the OS folder choice is mocked; snapshot/capture use the real local API. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(pathToFileURL(process.env.REPRISE_PLAYWRIGHT).href);
const [url,fixturePath]=process.argv.slice(2),fixture=JSON.parse(await fs.readFile(fixturePath,'utf8'));
const browser=await chromium.launch({headless:true,...(process.env.REPRISE_BROWSER?{executablePath:process.env.REPRISE_BROWSER}:{})});
const page=await browser.newPage({viewport:{width:1360,height:900}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));
const requests=[];
page.on('request',request=>{if(request.method()==='POST')requests.push({url:request.url(),body:request.postDataJSON()});});
await page.addInitScript(source=>{
 let choices=0;
 window.RepriseDesktop={chooseFolder:async()=>++choices===1?{status:'cancelled'}:{status:'selected',path:source,backend:'test-bridge'}};
},fixture.source);
const noMainExtras=async scope=>assert.equal(await page.locator(`${scope} [data-action=ai-settings],${scope} [data-action=ai-suggest],${scope} [data-action=content-storage],${scope} [data-action=content-transfer]`).count(),0);
try{
 await page.goto(`${url}?lang=en`);
 await page.waitForSelector('.first-run');
 await noMainExtras('body');
 assert.equal(await page.locator('.first-run [data-action=start-website-folder]').count(),1);
 assert.equal(await page.locator('.history').isVisible(),false);
 assert.doesNotMatch(await page.locator('.first-run').innerText(),/\p{Script=Han}/u,'English first task has no untranslated Chinese copy');
 await page.click('.chrome [data-language=zh]');
 assert.match(await page.locator('.first-run h1').innerText(),/改下一轮之前，留一稿/);
 assert.doesNotMatch((await page.locator('.first-run').innerText()).replace(/Reprise|AI/g,''),/[A-Za-z]/,'Chinese first task has no untranslated English copy');
 assert.equal(await page.evaluate(()=>state.project),null,'Language changes keep the empty workspace empty');
 await page.screenshot({path:fixture.root+'/first-run-zh.png'});
 await page.click('.chrome [data-language=en]');
 assert.match(await page.locator('.first-run h1').innerText(),/Save a draft before the next edit/);
 await page.screenshot({path:fixture.root+'/first-run-en.png'});
 await page.click('.first-run [data-action=start-website-folder]');
 await page.waitForSelector('[data-project-picker]');
 assert.equal(await page.evaluate(()=>state.project),null,'Cancelling does not select or join a project');
 assert.equal(requests.filter(r=>/\/api\/projects$/.test(r.url)).length,0);
 assert.equal(await page.locator('#content-import-kind,#content-import-exclusions').count(),0,'First task has no import modes or technical options');
 await page.click('#dialog .dialog-footer [data-action=close]');
 await page.click('.first-run [data-action=start-website-folder]');
 await page.waitForSelector('#content-version-title');
 assert.equal(requests.filter(r=>/\/snapshot$/.test(r.url)).length,0,'Folder choice alone does not save a draft');
 assert.equal(await page.locator('#recipe-json').count(),0);
 await page.click('#dialog .dialog-footer [data-action=close]');
 const project=await page.evaluate(()=>state.project.id);
 assert.doesNotMatch(await page.locator('#detail').innerText(),/\p{Script=Han}/u,'English empty project is usable before its first save');
 await page.click('.chrome [data-language=zh]');
 assert.match(await page.locator('#detail').innerText(),/保存第一稿/);
 assert.equal(await page.evaluate(()=>state.project.id),project);
 assert.equal(await page.evaluate(()=>state.commits.length),0);
 await page.click('.chrome [data-language=en]');
 await page.click('#detail [data-action=content-snapshot]');
 await page.fill('#content-version-title','Before changing the spacing');
 await page.click('#dialog [data-action=save-content-version]');
 await page.waitForFunction(()=>state.commits.length===1&&detail(state.selected)?.evidence.some(record=>record.status==='complete'),undefined,{timeout:30000});
 await page.waitForFunction(()=>document.querySelector('#draft-list img')?.naturalWidth>0);
 const sha=await page.evaluate(()=>state.selected);
 const capture=await page.evaluate(()=>detail(state.selected).evidence.find(record=>record.status==='complete'));
 assert.equal(capture.sha,sha);
 assert.ok(capture.items.length>0);
 assert.ok(capture.items.every(item=>item.sha===sha),'Every captured item is bound to the saved draft');
 const saves=requests.filter(r=>/\/snapshot$/.test(r.url));
 assert.equal(saves.length,1,'One explicit save produces the file version and image');
 assert.equal(saves[0].body.capture_static,true);
 assert.equal(await page.locator('.version-name h2').innerText(),'Before changing the spacing');
 assert.doesNotMatch(await page.locator('#detail').innerText(),/\p{Script=Han}/u,'English saved draft has no untranslated Chinese copy');
 const selectedContext=await page.evaluate(()=>({project:state.project.id,sha:state.selected,tab:state.tab}));
 await page.click('.chrome [data-language=zh]');
 assert.deepEqual(await page.evaluate(()=>({project:state.project.id,sha:state.selected,tab:state.tab})),selectedContext,'Language change preserves the selected project, draft and tab');
 assert.equal(await page.locator('.version-name h2').innerText(),'Before changing the spacing','User-entered draft name is preserved');
 assert.match(await page.locator('#detail').innerText(),/取出这一稿/);
 await page.screenshot({path:fixture.root+'/first-draft-zh.png'});
 await page.click('.chrome [data-language=en]');
 assert.deepEqual(await page.evaluate(()=>({project:state.project.id,sha:state.selected,tab:state.tab})),selectedContext);
 await page.screenshot({path:fixture.root+'/first-draft-en.png'});
 await page.click('#settings-toggle');
 await page.waitForSelector('#dialog.settings-dialog');
 await noMainExtras('#dialog');
 assert.equal(await page.locator('#dialog [data-action=confirm-stop-workbench]').count(),1);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.querySelector('#dialog').scrollWidth<=document.querySelector('#dialog').clientWidth),true);
 await page.screenshot({path:fixture.root+'/settings-mobile-en.png'});
 await page.click('#dialog [data-action=confirm-stop-workbench]');
 await page.click('#dialog .dialog-footer [data-action=close]');
 assert.equal(await page.locator('#dialog').evaluate(element=>element.classList.contains('settings-dialog')),true);
 await page.click('#dialog [data-action=confirm-stop-workbench]');
 await page.click('#dialog [data-action=stop-workbench]');
 await page.waitForFunction(()=>document.querySelector('#dialog-title')?.textContent==='Reprise stopped',undefined,{timeout:15000});
 assert.equal(requests.filter(r=>/\/ai\/suggest$/.test(r.url)).length,0);
 assert.deepEqual(errors,[]);
 await fs.writeFile(fixture.root+'/ui-result.json',JSON.stringify({ok:true,sha,ai_calls:0,ai_entries_absent:true,one_save_one_image:true,exact_revision_media:true,cancel_does_not_import:true,bilingual_first_run:true,bilingual_empty_project:true,bilingual_saved_draft:true,language_preserves_context:true,native_picker:'test bridge; not a real OS dialog',shutdown_confirmed:true,mobile_overflow:false,errors},null,2));
}catch(error){
 await page.screenshot({path:fixture.root+'/ui-failure.png',fullPage:true});
 await fs.writeFile(fixture.root+'/ui-failure.json',JSON.stringify({error:String(error),snapshot:await page.evaluate(()=>repriseWorkspace.snapshot()),dialog:await page.locator('#dialog').innerText()},null,2));
 throw error;
}finally{await browser.close();}
