 await page.fill('#content-import-path',noSource);
 await page.click('[data-action=save-content-project]');
 await page.waitForSelector('#initial-preview-choice');
 await page.selectOption('#initial-preview-choice','none');
 await page.click('[data-action=save-content-version]');
 await page.waitForFunction(()=>state.project.preview_preferences?.mode==='none'&&state.commits.length===1);
 const noProject=await page.evaluate(()=>state.project.id);
 assert.equal(await page.locator('#draft-list img').count(),0);
 await page.reload();
 await page.waitForFunction(id=>state.project?.id===id&&state.project.preview_preferences?.mode==='none',noProject);
 assert.equal(await page.locator('#initial-preview-choice').count(),0,'Reload does not ask again');
 await fs.appendFile(noSource+'/index.html','<p>Second files-only draft</p>');
 await page.click('#content-save');
 await page.waitForFunction(()=>state.commits.length===2);
 assert.equal(await page.locator('#dialog').evaluate(e=>e.open),false,'Later files-only saves need no dialog');
 assert.equal(await page.locator('#draft-list img').count(),0);
 await page.click('.chrome [data-action=content-projects]');
 await page.waitForSelector(`[data-action=content-open][data-project="${project}"]`);
 await page.click(`[data-action=content-open][data-project="${project}"]`);
 await page.waitForFunction(id=>state.project?.id===id&&state.commits.length===1,project);
 await page.click('#settings-toggle');
 await page.waitForSelector('#dialog.settings-dialog');
 await noMainExtras('#dialog');
 assert.equal(await page.locator('#dialog [data-keep-open=preview-help],#dialog [data-keep-open=project-activity]').count(),0);
 const languageSize=await page.locator('.settings-language .language-switch').evaluate(e=>({width:e.getBoundingClientRect().width,buttons:[...e.querySelectorAll('button')].map(b=>b.getBoundingClientRect().width)}));
 assert.ok(languageSize.width<=113&&Math.abs(languageSize.buttons[0]-languageSize.buttons[1])<1,'Language capsule has two compact equal segments');
 await page.click('#dialog [data-keep-open=saved-drafts] > summary');
