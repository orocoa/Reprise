/* Agent-selected repository -> historical preview -> restore/ZIP -> reload. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(pathToFileURL(process.env.REPRISE_PLAYWRIGHT).href);
const [url,fixturePath]=process.argv.slice(2),fixture=JSON.parse(await fs.readFile(fixturePath,'utf8'));
const browser=await chromium.launch({headless:true,...(process.env.REPRISE_BROWSER?{executablePath:process.env.REPRISE_BROWSER}:{})});
const page=await browser.newPage({viewport:{width:1360,height:900},acceptDownloads:true});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const state=()=>page.evaluate(()=>repriseWorkspace.snapshot());
const output=fixture.output||fixture.root;
try{
 const start=new URL(url);start.searchParams.set('lang','zh');
 await page.goto(start.href);
 await page.waitForFunction(()=>repriseWorkspace.snapshot().commits.length===2&&document.querySelector('[data-action=recovery]:not([disabled])'));
 assert.equal(await page.locator('[data-action=projects]').count(),0,'The agent selects the repository; there is no project chooser');
 await page.screenshot({animations:'disabled',path:output+'/workspace-desktop.png'});
 await page.click(`.version-row[data-id="${fixture.base}"]`);
 await page.waitForFunction(sha=>repriseWorkspace.snapshot().sha===sha&&!!document.querySelector('[data-action=recovery]:not([disabled])'),fixture.base);
 await page.click('[data-action=run]');
 await page.waitForSelector('#recipe-json',{state:'attached'});
 assert.equal(await page.locator('#recipe-json').isVisible(),false,'Static users need no raw JSON');
 await page.click('[data-action=save-recipe]');
 await page.waitForFunction(()=>!document.querySelector('#dialog').open);
 await page.click('[data-action=run]');
 await page.waitForFunction(sha=>state.runtimes.some(r=>r.sha===sha&&r.running&&r.url),fixture.base);
 await page.click('#tab-preview');
 await page.waitForSelector('[data-action=inline-preview]');
 await page.click('[data-action=inline-preview]');
 await page.frameLocator('.live-preview-frame').locator('h1').waitFor();
 assert.equal(await page.frameLocator('.live-preview-frame').locator('h1').innerText(),'first');
 await page.screenshot({animations:'disabled',path:output+'/historical-preview.png'});
 await page.click('[data-action=recovery]');
 await page.waitForSelector('#dialog [data-action=save-restore]:not([disabled])');
 assert.equal(await page.locator('#recovery-change-location').evaluate(element=>element.open),false,'Default recovery needs no path entry');
 assert.equal(await page.locator('#restore-path').isVisible(),false);
 const defaultRecovery=await page.locator('#restore-path').inputValue();
 assert.ok(defaultRecovery,'The dialog supplies a new recovery folder');
 assert.equal(path.dirname(defaultRecovery),path.dirname(fixture.source),'Default recovery belongs beside the original project');
 const relativeToState=path.relative(path.join(fixture.root,'state'),defaultRecovery);
 assert.ok(relativeToState==='..'||relativeToState.startsWith('..'+path.sep)||path.isAbsolute(relativeToState),'Default recovery stays outside Reprise data');
 assert.notEqual(defaultRecovery,fixture.source,'Default recovery must be a new folder');
 await page.click('[data-action=save-restore]');
 await page.waitForFunction(()=>document.querySelector('#dialog-title').textContent==='文件已取回');
 assert.match(await page.locator('#dialog').innerText(),/文件对象散列已校验/);
 assert.equal(await fs.readFile(defaultRecovery+'/index.html','utf8'),'<!doctype html><title>first</title><h1>first</h1>');
 await page.screenshot({animations:'disabled',path:output+'/restored-default.png'});
 await page.click('#dialog [data-action=close]');
 await page.click('[data-action=recovery]');
 const recovery=fixture.root+'/browser-recovered';
 await page.locator('#recovery-change-location > summary').click();
 await page.fill('#restore-path',recovery);
 await page.click('[data-action=save-restore]');
 await page.waitForFunction(()=>document.querySelector('#dialog-title').textContent==='文件已取回');
 assert.match(await page.locator('#dialog').innerText(),/文件对象散列已校验/);
 assert.equal(await fs.readFile(recovery+'/index.html','utf8'),'<!doctype html><title>first</title><h1>first</h1>');
 await page.screenshot({animations:'disabled',path:output+'/restored.png'});
 await page.click('#dialog [data-action=close]');
 await page.click('[data-action=recovery]');
 await page.locator('#recovery-change-location > summary').click();
 await page.fill('#restore-path',recovery);
 await page.click('[data-action=save-restore]');
 await page.waitForFunction(()=>document.querySelector('#dialog-status').textContent.includes('已经存在'));
 await page.click('#dialog [data-action=close]');
 await page.click('[data-action=recovery]');await page.locator('#dialog details').filter({has:page.locator('[data-action=save-export]')}).locator('summary').click();await page.click('[data-action=save-export]');
 await page.waitForSelector('#dialog a[download]');
 const pending=page.waitForEvent('download');await page.click('#dialog a[download]');
 const download=await pending;await download.saveAs(output+'/browser-version.zip');
 assert.equal(await download.failure(),null);
 await page.click('#dialog [data-action=close]');
 const selected=await state();await page.reload();
 await page.waitForFunction(sha=>repriseWorkspace.snapshot().sha===sha&&document.querySelector('[data-action=recovery]:not([disabled])'),selected.sha);
 assert.equal((await state()).projectId,selected.projectId);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Workspace fits narrow viewport');
 await page.screenshot({animations:'disabled',path:output+'/workspace-mobile.png'});
 await page.click('[data-action=recovery]');
 assert.equal(await page.evaluate(()=>document.querySelector('#dialog').scrollWidth<=document.querySelector('#dialog').clientWidth),true,'Recovery dialog fits narrow viewport');
 await page.screenshot({animations:'disabled',path:output+'/recovery-mobile.png'});
 await page.click('#dialog [data-action=close]');
 start.searchParams.set('lang','en');await page.goto(start.href);
 await page.waitForSelector('[data-action=recovery]:not([disabled])');
 assert.equal(await page.locator('[data-action=recovery]').innerText(),'Recover this draft');
 assert.deepEqual(errors,[]);
 await fs.writeFile(output+'/workflow-result.json',JSON.stringify({ok:true,errors,base:fixture.base,restored:recovery,defaultRecovery,defaultRecoveryWithoutInput:true,zip:output+'/browser-version.zip',agentSelectedProject:true,mobileWidths:[390],englishRecovery:true},null,2));
 console.log('Workspace workflow passed: agent project context, preview, recover, download, reload, mobile, English');
}finally{await browser.close();}
